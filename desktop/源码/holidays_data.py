def holiday_of(ds):
    """返回 (名称, 类型) 或 None"""
    return HOLIDAYS.get(ds)


def holiday_text(ds):
    h = HOLIDAYS.get(ds)
    if not h:
        return ""
    name, kind = h
    return f"{name}·放假" if kind == "off" else f"{name}·调休上班"
