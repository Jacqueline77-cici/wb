"""法定节假日与调休（依据国务院办公厅通知）
HOLIDAYS[日期] = (节日名, 'off' 放假 / 'work' 调休上班)
"""

from datetime import date, timedelta

HOLIDAYS = {}


def _add(year, name, start, end, workdays=()):
    d = date(year, start[0], start[1])
    e = date(year, end[0], end[1])
    while d <= e:
        HOLIDAYS[d.isoformat()] = (name, "off")
        d += timedelta(days=1)
    for w in workdays:
        HOLIDAYS[w] = (name, "work")


